    private void assignBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignBtnActionPerformed
        String selectedDoctor = (String) doctorCombo.getSelectedItem();
    String selectedManager = (String) managerCombo.getSelectedItem();

    if (selectedDoctor == null || selectedManager == null) {
        JOptionPane.showMessageDialog(this, "Please select both a doctor and a manager.");
    } else {
        String doctorId = selectedDoctor.split(" - ")[0];
        String managerId = selectedManager.split(" - ")[0];

        Assignment assignment = new Assignment(doctorId, managerId);

        AssignmentDAO dao = new AssignmentDAO();
        dao.saveAssignment(assignment);

        JOptionPane.showMessageDialog(this, "Doctor assigned successfully!");
    }
    }//GEN-LAST:event_assignBtnActionPerformed

