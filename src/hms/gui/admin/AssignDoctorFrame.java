private void loadDoctorsAndManagers() {
    UserDAO dao = new UserDAO();
    ArrayList<User> allUsers = dao.loadAllUsers();

    for (User u : allUsers) {
        if (u.getRole().equals("Doctor")) {
            doctorCombo.addItem(u.getUserId() + " - " + u.getName());
        } else if (u.getRole().equals("MedicalManager")) {
            managerCombo.addItem(u.getUserId() + " - " + u.getName());
        }
    }
}
