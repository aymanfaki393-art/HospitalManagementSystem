    private void loadPatients() {
    UserDAO dao = new UserDAO();
    ArrayList<User> allUsers = dao.loadAllUsers();

    for (User u : allUsers) {
        if (u.getRole().equals("Patient")) {
            patientCombo.addItem(u.getUserId() + " - " + u.getName());
        }
    }
}

private void loadPrescriptionData() {
    PrescriptionDAO dao = new PrescriptionDAO();
    ArrayList<Prescription> all = dao.loadAllPrescriptions();

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("Patient ID");
    model.addColumn("Medication");
    model.addColumn("Dosage");
    model.addColumn("Date");

    for (Prescription p : all) {
        model.addRow(new Object[]{p.getPatientId(), p.getMedication(), p.getDosage(), p.getDate()});
    }

    prescriptionsTable.setModel(model);
}





    
    

