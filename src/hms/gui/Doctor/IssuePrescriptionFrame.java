    private void savePrescriptionBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_savePrescriptionBtnActionPerformed
        String selectedPatient = (String) patientCombo.getSelectedItem();
    String patientId = selectedPatient.split(" - ")[0];

    String medication = medicationField.getText();
    String dosage = dosageField.getText();
    String date = java.time.LocalDate.now().toString();

    Prescription p = new Prescription("RX" + System.currentTimeMillis(), patientId, "D001", medication, dosage, date);

    PrescriptionDAO dao = new PrescriptionDAO();
    dao.savePrescription(p);

    JOptionPane.showMessageDialog(this, "Prescription issued successfully!");
    loadPrescriptionData();
    }//GEN-LAST:event_savePrescriptionBtnActionPerformed

