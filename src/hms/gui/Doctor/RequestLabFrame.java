    private void loadPatients() {
    UserDAO dao = new UserDAO();
    ArrayList<User> allUsers = dao.loadAllUsers();

    for (User u : allUsers) {
        if (u.getRole().equals("Patient")) {
            patientCombo.addItem(u.getUserId() + " - " + u.getName());
        }
    }
}
    
    private void loadRequestData() {
    LabRequestDAO dao = new LabRequestDAO();
    ArrayList<LabRequest> all = dao.loadAllRequests();

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("Patient ID");
    model.addColumn("Test Type");
    model.addColumn("Date");

    for (LabRequest r : all) {
        model.addRow(new Object[]{r.getPatientId(), r.getTestType(), r.getDate()});
    }

    requestsTable.setModel(model);
}
    
    
    

