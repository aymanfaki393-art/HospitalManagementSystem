    private void submitRequestBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_submitRequestBtnActionPerformed
        String selectedPatient = (String) patientCombo.getSelectedItem();
    String patientId = selectedPatient.split(" - ")[0];

    String testType = testTypeField.getText();
    String date = java.time.LocalDate.now().toString();

    LabRequest r = new LabRequest("LR" + System.currentTimeMillis(), patientId, "D001", testType, date);

    LabRequestDAO dao = new LabRequestDAO();
    dao.saveRequest(r);

    JOptionPane.showMessageDialog(this, "Lab/Imaging request submitted!");
    loadRequestData();
    }//GEN-LAST:event_submitRequestBtnActionPerformed

