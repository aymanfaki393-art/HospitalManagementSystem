    private void loadPatients() {
    UserDAO dao = new UserDAO();
    ArrayList<User> allUsers = dao.loadAllUsers();

    for (User u : allUsers) {
        if (u.getRole().equals("Patient")) {
            patientCombo.addItem(u.getUserId() + " - " + u.getName());
        }
    }
}
    private void loadConsultationData() {
    ConsultationDAO dao = new ConsultationDAO();
    ArrayList<Consultation> allConsultations = dao.loadAllConsultations();

    DefaultTableModel model = new DefaultTableModel();
    model.addColumn("Patient ID");
    model.addColumn("Vitals");
    model.addColumn("Notes");
    model.addColumn("Date");

    for (Consultation c : allConsultations) {
        model.addRow(new Object[]{c.getPatientId(), c.getVitals(), c.getNotes(), c.getDate()});
    }

    consultationsTable.setModel(model);
}

