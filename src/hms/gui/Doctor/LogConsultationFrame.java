    private void saveConsultationBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveConsultationBtnActionPerformed
String selectedPatient = (String) patientCombo.getSelectedItem();
    String patientId = selectedPatient.split(" - ")[0];

    String vitals = vitalsField.getText();
    String notes = notesField.getText();
    String date = java.time.LocalDate.now().toString();

    Consultation c = new Consultation("C" + System.currentTimeMillis(), patientId, "D001", vitals, notes, date);

    ConsultationDAO dao = new ConsultationDAO();
    dao.saveConsultation(c);

    JOptionPane.showMessageDialog(this, "Consultation logged successfully!");
    loadConsultationData();        // TODO add your handling code here:
    }//GEN-LAST:event_saveConsultationBtnActionPerformed

